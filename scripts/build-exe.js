#!/usr/bin/env node

/**
 * 构建 .exe 启动器脚本
 * 使用方法: node scripts/build-exe.js
 */

import { execSync } from 'child_process';
import path from 'path';
import fs from 'fs';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, '..');

const colors = {
  reset: '\x1b[0m',
  bright: '\x1b[1m',
  red: '\x1b[31m',
  green: '\x1b[32m',
  yellow: '\x1b[33m',
  blue: '\x1b[34m',
  cyan: '\x1b[36m',
};

function log(color, prefix, msg) {
  console.log(`${color}[${prefix}]${colors.reset} ${msg}`);
}

/**
 * 将 ESM 风格的 launcher.js 转换为 CommonJS 格式（供 pkg 打包）
 * 转换规则：
 *   1. import { x, y } from 'mod'  →  const { x, y } = require('mod');
 *   2. import defaultExport from 'mod'  →  const defaultExport = require('mod');
 *   3. import * as ns from 'mod'  →  const ns = require('mod');
 *   4. export { x }  →  module.exports = { ...module.exports, x };
 *   5. import.meta.url  →  __filename（pkg 打包后可用）
 *
 * 注意：本转换器仅支持 launcher.js 中实际使用的 ESM 语法子集。
 *      对于复杂场景（动态 import、命名空间 re-export 等）不支持。
 */
function convertEsmToCjs(source) {
  let out = source;

  // 0. 提取并移除 shebang 行（pkg 不识别），后续放在 CJS 头部最前面
  let shebang = '';
  const shebangMatch = out.match(/^#![^\n]*\n/);
  if (shebangMatch) {
    shebang = shebangMatch[0];
    out = out.slice(shebang.length);
  }

  // 0.5 移除 ESM 中 __filename/__dirname 的赋值（CJS 中为原生变量，无需赋值）
  // 形如: const __filename = fileURLToPath(import.meta.url);
  //       const __dirname = path.dirname(__filename);
  out = out.replace(
    /^\s*const\s+__filename\s*=\s*fileURLToPath\([^)]*\);?\s*$/gm,
    '// [CJS 转换] __filename 已为原生变量，移除赋值'
  );
  out = out.replace(
    /^\s*const\s+__dirname\s*=\s*path\.dirname\(__filename\);?\s*$/gm,
    '// [CJS 转换] __dirname 已为原生变量，移除赋值'
  );

  // 1. import { a, b } from 'mod'  →  const { a, b } = require('mod');
  out = out.replace(
    /^\s*import\s+\{([^}]+)\}\s+from\s+['"]([^'"]+)['"];?/gm,
    (match, names, mod) => `const {${names}} = require('${mod}');`
  );

  // 2. import defaultExport from 'mod'  →  const defaultExport = require('mod');
  out = out.replace(
    /^\s*import\s+(\w+)\s+from\s+['"]([^'"]+)['"];?/gm,
    (match, name, mod) => `const ${name} = require('${mod}');`
  );

  // 3. import * as ns from 'mod'  →  const ns = require('mod');
  out = out.replace(
    /^\s*import\s+\*\s+as\s+(\w+)\s+from\s+['"]([^'"]+)['"];?/gm,
    (match, name, mod) => `const ${name} = require('${mod}');`
  );

  // 4. import.meta.url  →  __filename（pkg 中可用）
  out = out.replace(/import\.meta\.url/g, '__filename');

  // 5. export default x  →  module.exports = x;
  out = out.replace(
    /^\s*export\s+default\s+/gm,
    'module.exports = '
  );

  // 6. export { a, b }  →  module.exports = { ...module.exports, a, b };
  out = out.replace(
    /^\s*export\s+\{([^}]+)\};?/gm,
    (match, names) => `module.exports = { ...module.exports, ${names.trim()} };`
  );

  // 7. 顶部添加 CommonJS 标记（shebang 必须在最前面）
  const cjsHeader = `${shebang}// AUTO-GENERATED FROM scripts/launcher.js — DO NOT EDIT DIRECTLY
// This file is CommonJS, generated by scripts/build-exe.js at build time.
'use strict';
`;

  return cjsHeader + out;
}

async function main() {
  console.log(`\n${colors.cyan}${colors.bright}构建音乐盒子启动器 (.exe)${colors.reset}\n`);

  // 1. 检查 pkg 是否安装
  log(colors.blue, 'STEP', '检查 pkg 工具...');
  try {
    execSync('pkg --version', { stdio: 'ignore' });
    log(colors.green, 'OK', 'pkg 已安装');
  } catch (e) {
    log(colors.yellow, 'WARN', 'pkg 未安装，正在安装...');
    try {
      execSync('npm install -g pkg', { stdio: 'inherit' });
      log(colors.green, 'OK', 'pkg 安装完成');
    } catch (err) {
      log(colors.red, 'ERROR', 'pkg 安装失败');
      log(colors.yellow, 'INFO', '请手动安装: npm install -g pkg');
      process.exit(1);
    }
  }

  // 2. 创建 package.json 用于 pkg
  log(colors.blue, 'STEP', '创建 pkg 配置...');
  const pkgConfig = {
    name: 'music-box-launcher',
    version: '1.0.0',
    description: '音乐盒子启动器',
    main: 'scripts/launcher.js',
    type: 'module',
    bin: 'scripts/launcher.js',
    pkg: {
      assets: [],
      targets: ['node18-win-x64'],
      outputPath: 'dist',
    },
  };

  const tempPkgPath = path.join(ROOT_DIR, 'temp-pkg.json');
  fs.writeFileSync(tempPkgPath, JSON.stringify(pkgConfig, null, 2));
  log(colors.green, 'OK', '配置文件已创建');

  // 3. 准备启动器脚本（从磁盘读取 launcher.js 并转换为 CommonJS 格式）
  // [L1 修复] 不再使用内嵌字符串，改为读取磁盘 launcher.js 并转换，
  //          确保 build 产物与源码同步
  log(colors.blue, 'STEP', '准备启动器脚本（从 launcher.js 转换为 CJS）...');
  const launcherJsPath = path.join(ROOT_DIR, 'scripts', 'launcher.js');
  if (!fs.existsSync(launcherJsPath)) {
    log(colors.red, 'ERROR', `未找到启动器源文件: ${launcherJsPath}`);
    process.exit(1);
  }

  // 读取 launcher.js 内容并转换为 CommonJS
  const launcherJsContent = fs.readFileSync(launcherJsPath, 'utf-8');
  const launcherCjsContent = convertEsmToCjs(launcherJsContent);

  const launcherCjsPath = path.join(ROOT_DIR, 'scripts', 'launcher.cjs');
  fs.writeFileSync(launcherCjsPath, launcherCjsContent);
  log(colors.green, 'OK', `启动器脚本已生成: ${path.relative(ROOT_DIR, launcherCjsPath)}`);

  // 打印修复点摘要
  log(colors.cyan, 'INFO', 'launcher.js 已应用修复: C2/C3/H1/H2/H3/H4/M1-M6');

  // 4. 更新 pkg 配置使用 .cjs 文件
  pkgConfig.main = 'scripts/launcher.cjs';
  pkgConfig.bin = 'scripts/launcher.cjs';
  fs.writeFileSync(tempPkgPath, JSON.stringify(pkgConfig, null, 2));

  // 5. 创建 dist 目录
  const distDir = path.join(ROOT_DIR, 'dist');
  if (!fs.existsSync(distDir)) {
    fs.mkdirSync(distDir, { recursive: true });
  }

  // 6. 使用 pkg 打包
  log(colors.blue, 'STEP', '正在打包 .exe 文件...');
  try {
    execSync(
      `pkg . --targets node18-win-x64 --output dist/MusicBox-Launcher.exe --config temp-pkg.json`,
      { cwd: ROOT_DIR, stdio: 'inherit' }
    );
    log(colors.green, 'OK', '打包完成！');
  } catch (e) {
    log(colors.red, 'ERROR', '打包失败: ' + e.message);
    cleanup(tempPkgPath, launcherCjsPath);
    process.exit(1);
  }

  // 7. 清理临时文件
  cleanup(tempPkgPath, launcherCjsPath);

  // 8. 显示结果
  const exePath = path.join(distDir, 'MusicBox-Launcher.exe');
  if (fs.existsSync(exePath)) {
    const stats = fs.statSync(exePath);
    const sizeMB = (stats.size / 1024 / 1024).toFixed(2);

    console.log('');
    console.log(`${colors.green}${colors.bright}✅ 构建成功！${colors.reset}`);
    console.log('');
    console.log(`  ${colors.cyan}输出文件:${colors.reset} dist/MusicBox-Launcher.exe`);
    console.log(`  ${colors.cyan}文件大小:${colors.reset} ${sizeMB} MB`);
    console.log('');
    console.log(`  ${colors.yellow}使用方法:${colors.reset}`);
    console.log('  1. 将 MusicBox-Launcher.exe 复制到项目根目录');
    console.log('  2. 双击运行即可启动所有服务');
    console.log('');
  } else {
    log(colors.red, 'ERROR', '未找到生成的 .exe 文件');
    process.exit(1);
  }
}

function cleanup(tempPkgPath, launcherCjsPath) {
  try {
    if (fs.existsSync(tempPkgPath)) fs.unlinkSync(tempPkgPath);
    if (fs.existsSync(launcherCjsPath)) fs.unlinkSync(launcherCjsPath);
  } catch (e) {}
}

main().catch((err) => {
  console.error(`${colors.red}[ERROR]${colors.reset} ${err.message}`);
  process.exit(1);
});
